/**
 * Набори даних варіанта.
 *  - 5 точок  — індивідуальний варіант (задано викладачем);
 *  - 10 і 20 точок — згенеровані скриптом scripts/gen-datasets.js на тому ж
 *    відрізку [0; 4] за формою варіанта з «шумом вимірювань» ±0.03.
 * Файл працює і в браузері (глобальний об'єкт DATASETS), і в Node.js (require).
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.DATASETS = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const toPoints = (arr) => ({ x: arr.map((p) => p[0]), y: arr.map((p) => p[1]) });

  return {
    5: {
      title: '5 точок (варіант)',
      ...toPoints([[0, 0.0], [1, 0.5], [2, 0.8], [3, 0.5], [4, 0.0]]),
    },
    10: {
      title: '10 точок',
      ...toPoints([[0, -0.003], [0.444, 0.177], [0.889, 0.449], [1.333, 0.665], [1.778, 0.763],
        [2.222, 0.767], [2.667, 0.669], [3.111, 0.457], [3.556, 0.176], [4, -0.027]]),
    },
    20: {
      title: '20 точок',
      ...toPoints([[0, -0.012], [0.211, 0.09], [0.421, 0.193], [0.632, 0.323], [0.842, 0.425],
        [1.053, 0.556], [1.263, 0.623], [1.474, 0.714], [1.684, 0.777], [1.895, 0.824],
        [2.105, 0.797], [2.316, 0.738], [2.526, 0.733], [2.737, 0.621], [2.947, 0.527],
        [3.158, 0.426], [3.368, 0.296], [3.579, 0.19], [3.789, 0.085], [4, 0.007]]),
    },
    /** Базова форма варіанта (інтерполяційний поліном 5 точок) — «еталон» для аналізу похибок. */
    reference(x) {
      return 0.8 - (x - 2) ** 2 / 3 + (x - 2) ** 4 / 30;
    },
  };
});
